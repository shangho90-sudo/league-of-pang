import * as THREE from 'three';
import {loadMapAssets,createMapAsset,updateAssetMotion} from '../src/render/mapAssets.js';
import {sharedUniforms} from '../src/render/terrain.js';
import {applyEnvironment} from '../src/render/scene.js';
await loadMapAssets();
sharedUniforms.uFowEnabled.value=0;
const renderer=new THREE.WebGLRenderer({antialias:true,preserveDrawingBuffer:true});
renderer.setSize(innerWidth,innerHeight);renderer.outputColorSpace=THREE.SRGBColorSpace;renderer.toneMapping=THREE.ACESFilmicToneMapping;renderer.toneMappingExposure=1.15;
document.body.appendChild(renderer.domElement);
const scene=new THREE.Scene();scene.background=new THREE.Color(0x10202b);applyEnvironment(renderer,scene);
scene.add(new THREE.HemisphereLight(0xd4e4ff,0x52604a,2));const sun=new THREE.DirectionalLight(0xffecd0,3);sun.position.set(-3,8,8);scene.add(sun);
const camera=new THREE.PerspectiveCamera(28,innerWidth/innerHeight,0.1,100);camera.position.set(0,7,27);camera.lookAt(0,1.1,0);
const ids=['minion-melee','minion-caster','golem','wolf','drake','colossus'];
const assets=ids.map((id,i)=>{const root=createMapAsset(id,0);root.scale.setScalar(2.6/root.userData.h);root.position.x=(i-2.5)*4;scene.add(root);return root;});
document.querySelector('#labels').innerHTML=ids.map(id=>`<span>${id}</span>`).join('');
const unit={moving:false,speedNow:2.8,action:null};
for(const a of assets)updateAssetMotion(a,0,0,unit,0);
renderer.render(scene,camera);
window.pose=(moving,time=1)=>{for(const a of assets)updateAssetMotion(a,0.2,time,{...unit,moving},0);renderer.render(scene,camera);};
window.DONE=true;
window.INFO=assets.filter(a=>['minion-caster','golem','colossus'].includes(a.userData.assetId)).map(a=>({id:a.userData.assetId,h:a.userData.h,bones:a.userData.animation.rest.map(r=>({name:r.bone.name,child:r.bone.children.map(c=>c.name),pos:r.position.toArray().map(v=>+v.toFixed(2))}))}));
